"""High-confidence manual review for page-level OCR grouping errors.

The source workbook places several independent B-type blocks on the same page.
The first OCR pass can merge those blocks when a question label is omitted or
when the answer bubbles are printed below the option bank.  This module keeps
the reviewed page image as the source of truth and replaces only the pages
whose boundaries and answer bubbles have been checked manually.
"""

from __future__ import annotations


def option(key: str, label: str) -> dict:
    return {"key": key, "label": label, "sourceText": f"{key}.{label}"}


def stem(text: str, answer: str) -> dict:
    letters = list(answer)
    return {
        "text": text,
        "answer": letters,
        "sourceText": f"{text} {answer}",
        "sourceY": 0,
        "answerMode": "多选" if len(letters) > 1 else "单选",
    }


def group(group_id: str, title: str, topic: str, lecture_ids: list[str], options: list[dict], stems: list[dict]) -> dict:
    return {
        "id": group_id,
        "page": int(group_id[1:3]),
        "title": title,
        "kind": "B",
        "kindLabel": "B型题",
        "options": options,
        "stems": stems,
        "sourceText": f"{title}（按原题页分组并结合讲义复核）",
        "reviewState": "已按原题页与讲义复核",
        "topic": topic,
        "lectureIds": lecture_ids,
    }


def opts(*items: tuple[str, str]) -> list[dict]:
    return [option(key, label) for key, label in items]


def stems(*items: tuple[str, str]) -> list[dict]:
    return [stem(text, answer) for text, answer in items]


def replace_page(payload: dict, page: int, replacements: list[dict]) -> None:
    old = payload["groups"]
    positions = [index for index, item in enumerate(old) if item.get("page") == page]
    if not positions:
        old.extend(replacements)
        return
    start, end = min(positions), max(positions) + 1
    old[start:end] = replacements


def page_topic(page: int) -> str:
    if page == 1:
        return "综合"
    if 2 <= page <= 20:
        return "呼吸"
    if 21 <= page <= 34:
        return "消化"
    if 35 <= page <= 41:
        return "肾脏"
    if 42 <= page <= 60:
        return "血液"
    if 61 <= page <= 68:
        return "内分泌"
    if 69 <= page <= 71:
        return "风湿"
    if 72 <= page <= 74:
        return "中毒"
    return "循环"


