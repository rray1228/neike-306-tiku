#!/usr/bin/env python3
"""Manual pathology page reconstructions verified against the source PDF.

These pages contain two-column or stacked matching groups that the generic OCR
splitter cannot separate reliably. Keeping the source structure explicit makes
future rebuilds deterministic and prevents questions, options and answers from
bleeding across group boundaries.
"""

from __future__ import annotations


def _option(key: str, label: str) -> dict:
    return {"key": key, "label": label, "sourceText": f"{key}.{label}"}


def _group(
    group_id: str,
    page: int,
    title: str,
    options: list[tuple[str, str]],
    stems: list[tuple[str, str]],
) -> dict:
    option_rows = [_option(key, label) for key, label in options]
    stem_rows = [
        {
            "text": text,
            "answer": list(answer),
            "answerMode": "多选" if len(answer) > 1 else "单选",
            "sourceText": f"{text}（{answer}）",
            "sourceY": None,
        }
        for text, answer in stems
    ]
    return {
        "id": group_id,
        "page": page,
        "title": title,
        "kind": "B",
        "kindLabel": "B型题",
        "options": option_rows,
        "stems": stem_rows,
        "sourceText": " | ".join(
            [*(row["sourceText"] for row in option_rows), *(row["sourceText"] for row in stem_rows)]
        ),
        "reviewState": "已按题册原图与讲义复核",
    }


